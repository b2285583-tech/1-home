// 1. var — переменная, которую можно переобъявлять и изменять.
// 2. let — переменная, которую можно изменять, но нельзя повторно объявить в той же области.
// 3. const — переменная, которую нельзя переназначить.

var name = "Ali";
let age = 15;
const city = "Bishkek";

// 1. String — текстовые данные
let userName = "Ali";

// 2. Number — числа
let number = 25;

// 3. Boolean — логическое значение (true или false)
let isStudent = true;

// 4. Undefined — переменная без заданного значения
let car;

// 5. Null — отсутствие значения
let job = null;

// 6. Object — объект с несколькими свойствами
let user = {
    name: "Ali",
    age: 15
};
